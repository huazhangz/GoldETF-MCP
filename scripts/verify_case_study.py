# Independent cross-check of the GVZ backtest with statsmodels + arch.
#   .venv/bin/python scripts/verify_case_study.py      (needs: pip install statsmodels arch)
# Re-runs the same rolling-origin evaluation as `ts_backtest` in scripts/case_study.ts and writes
# docs/case-study/gvz-crosscheck.md comparing the two implementations side by side.
import json
import math
import pathlib
import warnings

import numpy as np
import pandas as pd
from scipy import stats

warnings.simplefilter("ignore")
from arch import arch_model  # noqa: E402
from statsmodels.tsa.arima.model import ARIMA  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parent.parent
RESULTS = json.loads((ROOT / "docs/case-study/gvz-results.json").read_text())
END = RESULTS["sample_end"]
step = next(s for s in RESULTS["steps"] if s["tool"] == "ts_backtest")
INITIAL = step["args"]["initial_window"]
H = step["args"]["horizons"]

d = pd.read_csv("https://fred.stlouisfed.org/graph/fredgraph.csv?id=GVZCLS", parse_dates=["observation_date"])
d.columns = ["date", "v"]
d["v"] = pd.to_numeric(d["v"], errors="coerce")
d = d.dropna()
monthly = d.set_index("date")["v"].resample("MS").mean()
y = np.log(monthly[: END[:7]].values)
assert len(y) == RESULTS["steps"][0]["result"]["n"], "sample size differs from the MCP run"


def fit_forecast(kind, train, h):
    if kind[0] == "arima":
        order, trend = kind[1], kind[2]
        f = ARIMA(train, order=order, trend=trend).fit()
        fc = f.get_forecast(h)
        return fc.predicted_mean, np.sqrt(fc.var_pred_mean), math.inf
    lags, vol = kind[1], kind[2]
    am = arch_model(train * 10, mean="AR", lags=lags, vol=vol, dist="t", rescale=False).fit(disp="off")
    fc = am.forecast(horizon=h, reindex=False)
    # arch's `variance` already includes AR propagation of earlier shocks.
    return fc.mean.values[0] / 10, np.sqrt(fc.variance.values[0]) / 10, am.params["nu"]


MODELS = {
    "RW": ("arima", (0, 1, 0), "n"),
    "RW+drift": ("arima", (0, 1, 0), "t"),
    "ARIMA(1,1,1)": ("arima", (1, 1, 1), "t"),
    "ARIMA(2,1,2)": ("arima", (2, 1, 2), "t"),
    "ARIMA(1,0,0)": ("arima", (1, 0, 0), "c"),
    "AR(1)-t": ("vol", 1, "Constant"),
    "AR(1)-GARCH(1,1)-t": ("vol", 1, "GARCH"),
}

rows = {m: {h: [] for h in H} for m in MODELS}
for o in range(INITIAL, len(y)):
    for m, kind in MODELS.items():
        mu, sd, nu = fit_forecast(kind, y[:o], max(H))
        for h in H:
            if o + h - 1 < len(y):
                rows[m][h].append((y[o + h - 1], mu[h - 1], sd[h - 1], nu))


def logscore(yt, mu, sd, nu):
    if math.isinf(nu):
        return stats.norm.logpdf(yt, mu, sd)
    sc = sd * math.sqrt((nu - 2) / nu)
    return stats.t.logpdf((yt - mu) / sc, nu) - math.log(sc)


def dm_p(e1, e2, h):
    dlt = e1**2 - e2**2
    n = len(dlt)
    db = dlt.mean()
    g = [np.sum((dlt[k:] - db) * (dlt[: n - k] - db)) / n for k in range(h)]
    v = g[0] + 2 * sum(g[1:])
    s = db / math.sqrt(v / n) * math.sqrt((n + 1 - 2 * h + h * (h - 1) / n) / n)
    return 2 * stats.t.sf(abs(s), n - 1)


mcp = {h["horizon"]: {m["model"]: m for m in h["models"]} for h in step["result"]["results"]}
out = [
    "# Cross-check: MCP tools vs statsmodels/arch",
    "",
    f"Same data (GVZCLS monthly mean, log, n = {len(y)}), same {len(y) - INITIAL} origins, expanding window.",
    "Generated by `scripts/verify_case_study.py`. Columns: relative RMSE vs RW, DM p-value, log score.",
    "",
]
for h in H:
    e_rw = np.array([r[0] - r[1] for r in rows["RW"][h]])
    out += [f"**h = {h}**", "", "| model | rel RMSE (MCP / Python) | DM p (MCP / Python) | log score (MCP / Python) |", "|---|---|---|---|"]
    for m in MODELS:
        a = np.array([[r[0], r[1]] for r in rows[m][h]])
        e = a[:, 0] - a[:, 1]
        rel = math.sqrt(np.mean(e**2)) / math.sqrt(np.mean(e_rw**2))
        ls = np.mean([logscore(*r) for r in rows[m][h]])
        p = "—" if m == "RW" else f"{dm_p(e, e_rw, h):.3f}"
        t = mcp[h][m]
        out.append(f"| {m} | {t['rel_rmse']} / {rel:.4f} | {t.get('dm_p', '—')} / {p} | {t['log_score']} / {ls:.4f} |")
    out.append("")
out += [
    "RW, RW+drift, ARIMA(1,0,0) and AR(1)-t agree to the reported precision. The remaining gaps come from the optimizers,",
    "not the models: the likelihood functions agree to 1e-7 or better at identical parameters (test/stats/models.test.ts).",
    "- ARIMA(1,1,1) / ARIMA(2,1,2): the likelihood is multimodal. On the full sample statsmodels' ARIMA(1,1,1) optimum",
    "  (ar -0.59, ma 0.64) has a log-likelihood 4.1 below the MCP optimum (ar 0.84, ma -0.96); the higher optimum has an",
    "  MA root near 1 that cancels the differencing, i.e. it is the over-differenced fit, and it forecasts worse.",
    "- AR(1)-GARCH(1,1)-t: alpha is ~0, so the likelihood is flat in (alpha, beta) and the two optimizers stop at slightly",
    "  different points.",
]
(ROOT / "docs/case-study/gvz-crosscheck.md").write_text("\n".join(out) + "\n")
print("\n".join(out))
